export const ALL_CHAMPIONS_SORTED: string[] = Array.from(
  new Set([
    ...DEFAULT_CHAMPION_POOLS.top,
    ...DEFAULT_CHAMPION_POOLS.jgl,
    ...DEFAULT_CHAMPION_POOLS.mid,
    ...DEFAULT_CHAMPION_POOLS.adc,
    ...DEFAULT_CHAMPION_POOLS.sup,
    ...Object.keys(CHAMPION_ID_MAP)
  ])
).sort((a, b) => a.localeCompare(b));

export const getChampionId = (name: string): string => {
  if (CHAMPION_ID_MAP[name]) return CHAMPION_ID_MAP[name];
  // Fallback normalize name: remove spaces, apostrophes, dots
  return name.replace(/[^a-zA-Z0-9]/g, '');
};

export const getChampionImages = (name: string) => {
  const id = getChampionId(name);
  const version = "14.23.1";
  return {
    id,
    name,
    icon: `https://ddragon.leagueoflegends.com/cdn/${version}/img/champion/${id}.png`,
    loading: `https://ddragon.leagueoflegends.com/cdn/img/champion/loading/${id}_0.jpg`,
    splash: `https://ddragon.leagueoflegends.com/cdn/img/champion/splash/${id}_0.jpg`,
  };
};
